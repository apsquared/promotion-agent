const round = n => Math.round(n * 1000) / 1000;
const clamp = (n, lo, hi) => Math.min(hi, Math.max(lo, n));
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// Inline markdown: **bold**, *em*, `code` and links (shown as underlined text). Every word becomes one streamed unit.
function inline(text, counter) {
  const parts = String(text).split(/(\*\*[^*]+\*\*|`[^`]+`|\*[^*\s][^*]*\*|\[[^\]]+\]\([^)\s]+\))/);
  return parts.map(part => {
    if (!part) return '';
    let tag = null, body = part;
    if (/^\*\*.+\*\*$/.test(part)) { tag = 'strong'; body = part.slice(2, -2); }
    else if (/^`.+`$/.test(part)) { tag = 'code'; body = part.slice(1, -1); }
    else if (/^\*.+\*$/.test(part)) { tag = 'em'; body = part.slice(1, -1); }
    else if (/^\[/.test(part)) { tag = 'u'; body = part.slice(1, part.indexOf(']')); }
    const spans = (body.match(/\s*\S+\s*/g) || []).map(word => { counter.units++; return `<span class="w">${esc(word)}</span>`; }).join('');
    return tag ? `<${tag}>${spans}</${tag}>` : spans;
  }).join('');
}

// Block markdown: paragraphs, headings, bullet and numbered lists, fenced code (one unit per line).
export function markdown(src) {
  const counter = { units: 0 };
  const lines = String(src).replace(/\r/g, '').split('\n');
  const isBlockStart = l => /^```|^#{1,4}\s|^\s*[-*]\s+|^\s*\d+[.)]\s+/.test(l);
  let html = '', i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim()) { i++; continue; }
    if (line.startsWith('```')) {
      const code = [];
      i++;
      while (i < lines.length && !lines[i].startsWith('```')) code.push(lines[i++]);
      i++;
      counter.units += code.length;
      html += `<pre>${code.map(l => `<span class="w">${esc(l) || ' '}\n</span>`).join('')}</pre>`;
      continue;
    }
    const heading = line.match(/^#{1,4}\s+(.*)/);
    if (heading) { html += `<h3>${inline(heading[1], counter)}</h3>`; i++; continue; }
    const list = line.match(/^\s*([-*]|\d+[.)])\s+/);
    if (list) {
      const ordered = /\d/.test(list[1]);
      const pattern = ordered ? /^\s*\d+[.)]\s+/ : /^\s*[-*]\s+/;
      const items = [];
      while (i < lines.length && pattern.test(lines[i])) items.push(lines[i++].replace(pattern, ''));
      const tag = ordered ? 'ol' : 'ul';
      counter.units += items.length;
      html += `<${tag}>${items.map((item, n) => `<li><span class="w mk">${ordered ? `${n + 1}.` : '•'}</span>${inline(item, counter)}</li>`).join('')}</${tag}>`;
      continue;
    }
    const para = [];
    while (i < lines.length && lines[i].trim() && !isBlockStart(lines[i])) para.push(lines[i++].trim());
    html += `<p>${inline(para.join(' '), counter)}</p>`;
  }
  return { html, units: counter.units };
}

function captionOf(beat) {
  if (beat.caption == null) return null;
  return typeof beat.caption === 'string' ? { eyebrow: '', text: beat.caption } : { eyebrow: beat.caption.eyebrow ?? '', text: beat.caption.text ?? '' };
}

export function validate(replay, projectDir) {
  const errors = [], warnings = [];
  if (!replay || typeof replay !== 'object') return { errors: ['Replay must be a JSON object.'], warnings };
  if (replay.version !== 1) errors.push('version must be 1.');
  if (!SKINS[replay.skin]) errors.push(`skin must be one of: ${Object.keys(SKINS).join(', ')}.`);
  if (replay.aspect && replay.aspect !== '16:9') errors.push('Only aspect 16:9 is supported so far.');
  if (!replay.source) errors.push('source must name the transcript the beats were cleaned from (for example transcript.md).');
  if (replay.disclosure === false) warnings.push('disclosure is off: say in the post copy that this is a recreation of a real session.');
  if (replay.sidebar != null) {
    const { project, threads = [], projects = [] } = replay.sidebar;
    const names = [project ?? '', ...(Array.isArray(threads) ? threads : [null]), ...(Array.isArray(projects) ? projects : [null])];
    if (!names.every(n => typeof n === 'string' && n.length <= 40) || threads.length > 4 || projects.length > 4)
      errors.push('sidebar takes project (a name), threads and projects (up to 4 names each), every name 40 characters or fewer.');
  }
  if (!Array.isArray(replay.beats) || !replay.beats.length) { errors.push('beats must be a non-empty array.'); return { errors, warnings }; }
  const seen = new Map();
  replay.beats.forEach((beat, index) => {
    const where = `beats[${index}]${beat?.id ? ` (${beat.id})` : ''}`;
    if (!beat || !TYPES.includes(beat.type)) { errors.push(`${where}: type must be one of ${TYPES.join(', ')}.`); return; }
    const id = beat.id ?? `b${index + 1}`;
    if (!/^[a-z][a-z0-9_-]*$/i.test(id)) errors.push(`${where}: id must start with a letter and use only letters, digits, - and _.`);
    if (seen.has(id)) errors.push(`${where}: duplicate id ${id}.`);
    seen.set(id, beat.type);
    if (SOURCED.includes(beat.type) && !beat.from) errors.push(`${where}: ${beat.type} beats need "from", the transcript turn(s) they come from.`);
    if (beat.type === 'user') {
      if (!beat.text?.trim()) errors.push(`${where}: user text is empty.`);
      else if ([...beat.text].length > MAX_USER_CHARS) errors.push(`${where}: user text is ${[...beat.text].length} characters; shorten it to ${MAX_USER_CHARS} or fewer so it can be read as it is typed.`);
    }
    if (beat.type === 'assistant') {
      if (!beat.text?.trim()) errors.push(`${where}: assistant text is empty.`);
      else {
        const { units } = markdown(beat.text);
        if (units > 140) warnings.push(`${where}: ${units} words will stream for a long time; trim to the gist.`);
      }
    }
    if (beat.type === 'tool' && !beat.name) errors.push(`${where}: tool beats need the tool's real name.`);
    if (beat.type === 'widget') {
      if (!/^assets\/[^/].*\.(png|jpe?g|webp|svg)$/i.test(beat.src ?? '')) errors.push(`${where}: widget src must be an image under assets/ (png, jpg, webp or svg).`);
      else if (projectDir && !existsSync(join(projectDir, beat.src))) errors.push(`${where}: ${beat.src} does not exist in the project.`);
    }
    if (beat.type === 'focus') {
      const target = seen.get(beat.target);
      if (!target || beat.target === id) errors.push(`${where}: focus target must be the id of an earlier beat.`);
      else if (target === 'focus' || target === 'pause') errors.push(`${where}: focus target ${beat.target} is not visible on screen.`);
      if (beat.scale != null && !(beat.scale >= 1 && beat.scale <= 1.5)) errors.push(`${where}: scale must be between 1 and 1.5.`);
      if (beat.label && beat.label.length > 40) errors.push(`${where}: focus label should be 40 characters or fewer.`);
    }
    for (const key of ['duration', 'hold', 'wps', 'realSeconds'])
      if (beat[key] != null && !(typeof beat[key] === 'number' && beat[key] >= 0)) errors.push(`${where}: ${key} must be a non-negative number.`);
    const caption = captionOf(beat);
    if (caption && !caption.text) errors.push(`${where}: caption needs text.`);
    if (caption && caption.text.length > MAX_CAPTION_CHARS) errors.push(`${where}: caption is ${caption.text.length} characters; keep it to ${MAX_CAPTION_CHARS} so it fits on one line.`);
  });
  if (replay.beats.some(captionOf) && !captionOf(replay.beats[0])) warnings.push('The first beat has no caption, so the first frame (the thumbnail) shows an empty chat.');
  return { errors, warnings };
}

// Turns beats into absolute times. Rendering units must match the DOM the composer writes.
export function plan(replay) {
  const pace = replay.pace ?? {};
  let t = LEAD;
  const beats = replay.beats.map((beat, index) => {
    const p = { id: beat.id ?? `b${index + 1}`, type: beat.type, start: round(t) };
    if (beat.type === 'user') {
      p.typing = round(clamp([...beat.text].length / (pace.charsPerSecond ?? 32), 0.5, 3));
      p.send = round(t + p.typing + 0.3);
      p.end = p.send + 0.6;
    } else if (beat.type === 'thinking') {
      p.end = t + (beat.duration ?? 1.2);
    } else if (beat.type === 'tool') {
      p.done = round(t + 0.3 + (beat.duration ?? 1.4));
      p.end = p.done + (beat.output ? 0.8 : 0.4);
    } else if (beat.type === 'assistant') {
      p.units = markdown(beat.text).units;
      p.wps = beat.wps ?? pace.wordsPerSecond ?? 18;
      p.end = t + p.units / p.wps + clamp(p.units * 0.06, 0.8, 2.5);
    } else if (beat.type === 'widget') {
      p.end = t + 0.4 + (beat.duration ?? 2.5);
    } else if (beat.type === 'focus') {
      p.target = beat.target;
      p.scale = beat.scale ?? 1.25;
      p.end = t + Math.max(2.4, beat.duration ?? 3);
    } else {
      p.end = t + (beat.duration ?? 1);
    }
    p.end = round(p.end + (beat.hold ?? 0));
    t = p.end;
    return p;
  });
  const captions = [];
  replay.beats.forEach((beat, index) => {
    const caption = captionOf(beat);
    if (caption) captions.push({ id: `cap${captions.length + 1}`, start: index === 0 ? 0 : beats[index].start, ...caption });
  });
  return { beats, captions, duration: round(t + TAIL) };
}

