      tl.fromTo(label, { opacity: 0, y: 6 }, { opacity: 1, y: 0, duration: 0.25, ease: 'power2.out' }, b.start + 0.85);
      tl.to(label, { opacity: 0, duration: 0.15 }, b.end - 0.95);
