    const k = b.scale, px = (box.x0 + box.x1) / 2, py = (box.y0 + box.y1) / 2;
    const qx = px + (P.width / 2 - px) * 0.6, qy = py + (P.height / 2 - py) * 0.6;
    const map = (x, y) => [qx + (x - px) * k, qy + (y - py) * k];
    const [x0, y0] = map(box.x0 - 6, box.y0 - 6), [x1, y1] = map(box.x1 + 6, box.y1 + 6);
    tl.to(camera, { scale: k, x: qx - k * px, y: qy - k * py, duration: 0.8, ease: 'power2.inOut' }, b.start);
    tl.to(camera, { scale: 1, x: 0, y: 0, duration: 0.8, ease: 'power2.inOut' }, b.end - 0.8);
    const ring = $(b.id + '_ring');
    Object.assign(ring.style, { left: x0 + 'px', top: y0 + 'px', width: (x1 - x0) + 'px', height: (y1 - y0) + 'px' });
