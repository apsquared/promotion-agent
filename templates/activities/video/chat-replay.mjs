const sizeAttrs = size => (size ? ` width="${size.width}" height="${size.height}"` : '');

// Intrinsic size of a PNG or SVG widget, so its box is laid out before the image loads.
export function imageSize(file) {
  try {
    const bytes = readFileSync(file);
    if (bytes.subarray(1, 4).toString('latin1') === 'PNG') return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
    if (/\.svg$/i.test(file)) {
      const tag = bytes.toString('utf8').match(/<svg\b[^>]*>/i)?.[0] ?? '';
      const attr = name => Number(tag.match(new RegExp(`\\s${name}="([\\d.]+)(px)?"`))?.[1]);
      const box = tag.match(/viewBox="[\d.-]+[\s,]+[\d.-]+[\s,]+([\d.]+)[\s,]+([\d.]+)"/);
      const width = attr('width') || Number(box?.[1]), height = attr('height') || Number(box?.[2]);
      if (width > 0 && height > 0) return { width, height };
    }
  } catch {}
  return null;
}

function beatHtml(beat, p, replay, projectDir) {
  const id = p.id;
  if (beat.type === 'user') return `<div class="beat user" id="${id}"><div class="bubble">${esc(beat.text)}</div></div>`;
  if (beat.type === 'thinking') {
    const [running, timed, untimed] = SKINS[replay.skin].thinking;
    const done = beat.realSeconds ? timed.replace('{t}', elapsed(beat.realSeconds)) : untimed;
    return `<div class="beat thinking" id="${id}"><span id="${id}_a">${esc(running)}</span><span class="done" id="${id}_b">${esc(done)}</span></div>`;
  }
  if (beat.type === 'tool') {
    const server = beat.server ?? replay.connector ?? '';
    const head = `<div class="beat tool" id="${id}"><div class="tool-head"><span class="tool-icon"><span class="spin" id="${id}_spin"></span><span class="ok" id="${id}_ok">${CHECK}</span></span>`
      + `<span class="tool-name">${SKINS[replay.skin].toolVerb ? `<span class="tool-verb">${esc(SKINS[replay.skin].toolVerb)}</span>` : ''}<b>${esc(beat.name)}</b>${server ? `<span class="tool-server">${esc(server)}</span>` : ''}</span>`
      + `<span class="tool-status"><span id="${id}_run">Running…</span><span id="${id}_sum">${esc(beat.status ?? 'Done')}</span></span></div>`
      + `${beat.input ? `<div class="tool-input">${esc(beat.input)}</div>` : ''}</div>`;
    return head + (beat.output ? `<div class="beat tool-output" id="${id}_out">${esc(beat.output)}</div>` : '');
  }
  if (beat.type === 'assistant') return `<div class="beat md" id="${id}">${markdown(beat.text).html}</div>`;
  if (beat.type === 'widget') {
    const label = beat.label ?? beat.server ?? replay.connector ?? '';
    return `<div class="beat widget" id="${id}">${label ? `<div class="widget-head">${esc(label)}</div>` : ''}<img src="${esc(beat.src)}"${sizeAttrs(projectDir && imageSize(join(projectDir, beat.src)))} alt="${esc(beat.alt ?? label)}"></div>`;
  }
  return '';
}

// Decorative chrome only: placeholder shapes, the conversation's own title, and the names replay.sidebar gives (bars without them).
function sidebar(skin, replay) {
  if (skin.sidebar !== 'threads') return '<div id="rail"><span class="rail-i"></span><span class="rail-i"></span><span class="rail-i"></span></div>';
  const { project, threads, projects } = replay.sidebar ?? {};
  const name = text => (text ? esc(text) : '<span class="rail-bar"></span>');
  const row = (cls, icon, text) => `<div class="rail-row${cls}">${icon}${name(text)}</div>`;
  const list = (names, count) => (names ?? Array(count).fill(''));
  return `<div id="rail" class="threads"><div class="win"><i></i><i></i><i></i></div><div class="rail-body">`
    + `<div class="strip">${'<span class="rail-i"></span>'.repeat(6)}<span class="rail-me"></span></div><div class="rail-list">`
    + row(' new', PENCIL, 'New chat') + '<div class="rail-head">Projects</div>' + row('', FOLDER, project)
    + row(' sub on', '', replay.title) + list(threads, 2).map(t => row(' sub', '', t)).join('')
    + list(projects, 3).map(p => row('', FOLDER, p)).join('') + '</div></div></div>';
}

