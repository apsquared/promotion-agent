export function compose(replay, projectDir) {
  const skin = SKINS[replay.skin];
  const timing = plan(replay);
  const layout = timing.captions.length ? { scale: 1.4, left: 232, top: 150 } : { scale: 1.55, left: 154, top: 60 };
  const disclosure = replay.disclosure === false ? '' : replay.disclosure ?? 'Recreated from a real session';
  const thread = replay.beats.map((beat, i) => beatHtml(beat, timing.beats[i], replay, projectDir)).filter(Boolean).join('\n              ');
  const drafts = replay.beats.map((beat, i) => beat.type === 'user'
    ? `<div class="draft" id="d_${timing.beats[i].id}">${[...beat.text].map(ch => `<span class="c">${esc(ch)}</span>`).join('')}</div>` : '').filter(Boolean).join('');
  const overlays = timing.beats.filter(b => b.type === 'focus').map(b => {
    const label = replay.beats.find((beat, i) => timing.beats[i].id === b.id).label;
    return `<div class="ring" id="${b.id}_ring"></div>${label ? `<div class="label" id="${b.id}_label">${esc(label)}</div>` : ''}`;
  }).join('');
  const captions = timing.captions.map(c => `<div class="cap" id="${c.id}">${c.eyebrow ? `<div class="eyebrow">${esc(c.eyebrow)}</div>` : ''}<div class="headline">${esc(c.text)}</div></div>`).join('');
  const data = { scale: layout.scale, left: layout.left, top: layout.top, width: W, height: H, duration: timing.duration, beats: timing.beats, captions: timing.captions };
  const html = `<!doctype html>
${MARKER}
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${W}, height=${H}" />
    <title>${esc(replay.title ?? 'Chat replay')}</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <style>${css(skin, layout)}
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${timing.duration}" data-width="${W}" data-height="${H}">
      <div id="stage" class="clip" data-start="0" data-duration="${timing.duration}" data-track-index="0">
        <div id="ground"></div>
        <div id="camera">
          <div id="app" data-layout-allow-overflow>
            ${sidebar(skin, replay)}
            <div id="main">
              <div id="topbar"><span id="convTitle">${skin.sidebar === 'threads' ? FOLDER : ''}${esc(replay.title ?? '')}</span>${disclosure ? `<span id="disclosure">${esc(disclosure)}</span>` : ''}</div>
              <div id="viewport" data-layout-allow-overflow><div id="thread"><div id="column">
              ${thread}
              </div></div></div>
              <div id="composerWrap"><div id="composer">
                <div id="draftArea" data-layout-allow-overlap><div id="placeholder">${esc(skin.placeholder)}</div>${drafts}</div>
                <div id="composerBar">${skin.composerLeft ?? '<span class="bar-i"></span><span class="bar-i"></span>'}${replay.model ? `<span id="model">${esc(replay.model)}</span>` : '<span id="model"></span>'}<span id="send">↑</span></div>
              </div></div>
            </div>
          </div>
        </div>
        ${timing.captions.length ? `<div id="captions" data-layout-allow-overlap>${captions}</div>` : ''}
        ${overlays}
      </div>
    </div>
    <script>
      const PLAN = ${JSON.stringify(data)};
${RUNTIME}
    </script>
  </body>
</html>
`;
  return { html, timing };
}

export function snapshotTimes(timing) {
  const times = new Set([0]);
  for (const b of timing.beats) {
    if (b.type === 'focus') times.add(round(b.start + 1.2));
    times.add(round(Math.max(0, b.end - 0.1)));
  }
  times.add(round(timing.duration - 0.1));
  return [...times].sort((a, b) => a - b);
}

function main(argv) {
  const args = argv.filter(a => !a.startsWith('--')), flags = new Set(argv.filter(a => a.startsWith('--')));
  if (!args[0]) {
    console.error('Usage: node chat-replay.mjs <replay.json> [project-dir] [--check] [--force]');
    return 2;
  }
  const replayPath = resolve(args[0]), projectDir = resolve(args[1] ?? dirname(replayPath));
  let replay;
  try { replay = JSON.parse(readFileSync(replayPath, 'utf8')); }
  catch (error) { console.error(`Cannot read ${replayPath}: ${error.message}`); return 1; }
  const { errors, warnings } = validate(replay, projectDir);
  for (const w of warnings) console.warn(`warning: ${w}`);
  if (errors.length) { for (const e of errors) console.error(`error: ${e}`); return 1; }
  const { html, timing } = compose(replay, projectDir);
  for (const b of timing.beats) console.log(`${b.start.toFixed(2).padStart(6)} → ${b.end.toFixed(2).padStart(6)}  ${b.type.padEnd(9)} ${b.id}`);
  console.log(`Duration: ${timing.duration}s`);
  console.log(`Snapshot times: ${snapshotTimes(timing).join(',')}`);
  if (flags.has('--check')) return 0;
  const out = join(projectDir, 'index.html');
  if (existsSync(out) && !readFileSync(out, 'utf8').includes(MARKER) && !flags.has('--force')) {
    console.error(`${out} was not generated by chat-replay.mjs. Re-run with --force to replace it (for example the blank starter from hyperframes init).`);
    return 1;
  }
  writeFileSync(out, html);
  console.log(`Wrote ${out}`);
  return 0;
}

